def check_essence(essence: str) -> Dict[str, Any]:
    """实质定义压缩规则校验：1-2 句/每句<=40 汉字/无营销词/非照抄官方描述。"""
    problems: List[str] = []
    sentences = [s for s in essence.replace("？", "。").replace("！", "。").split("。") if s]
    if not (1 <= len(sentences) <= ESSENCE_MAX_SENTENCES):
        problems.append("句数不在 1-2（实 {}）".format(len(sentences)))
    for s in sentences:
        if len(s) > ESSENCE_MAX_CHARS:
            problems.append("单句超 40 字：{}".format(s[:20]))
    for w in ESSENCE_MARKETING_WORDS:
        if w in essence:
            problems.append("营销词违禁：{}".format(w))
    return {"pass": not problems, "problems": problems}


