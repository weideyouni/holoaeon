def resolve_duplicates(records: List[Dict[str, Any]]) -> Dict[str, Any]:
    """跨维去重：同一仓库跨维重复时保留"综合分最高"的那一维为主记录，
    其余维度写 see-also 引用不重复计数（平分时按维度编号小者为主——确定性）。"""
    by_repo: Dict[str, List[Dict[str, Any]]] = {}
    for r in records:
        by_repo.setdefault(r["repo"], []).append(r)
    dup_notes: List[Dict[str, Any]] = []
    kept: List[Dict[str, Any]] = []
    for repo, items in sorted(by_repo.items()):
        if len(items) == 1:
            kept.extend(items)
            continue
        scored = []
        for it in items:
            s = composite_score(it)
            scored.append((s if s is not None else -1.0, it))
        scored.sort(key=lambda t: (-t[0], t[1].get("dim_id", "D99")))
        main = scored[0][1]
        kept.append(main)
        dup_notes.append({"repo": repo,
                         "dims": [it.get("dim_id") for it in items],
                         "resolution": "保留主维 {}，其余标注 see-also".format(main.get("dim_id"))})
    return {"kept": kept, "duplicates": dup_notes,
            "total_actual": len(kept),
            "note": "去重不重复计数——实际总数可能小于 180，须在 coverage_report 如实说明（素材口径采信）"}


def validate_dim_record(record: Dict[str, Any]) -> Dict[str, Any]:
    """维度 JSON 校验（素材验收清单 1/3/4/5 条的机器口径）。"""
    problems: List[str] = []
    for f in DIM_RECORD_REQUIRED:
        if f == "shortfall":
            continue  # 素材模板原文："若不足 10 条说明原因；否则 null"——null 合法
        if f not in record or record[f] in (None, "", []):
            problems.append("维度记录缺字段或空值：{}".format(f))
    results = record.get("results") or []
    if not results and not record.get("shortfall"):
        problems.append("results 空且 shortfall 缺失（缺口原因必说明）")
    for r in results:
        for f in RESULT_REQUIRED:
            if f not in r:
                problems.append("结果项缺字段：{}".format(f))
        es = check_essence(r.get("essence", ""))
        problems.extend("essence：" + p for p in es["problems"])
        if r.get("essence") and r.get("official_desc") and r["essence"] == r["official_desc"]:
            problems.append("essence 照抄官方描述")
        mapping = r.get("dimension_mapping")
        if mapping == "可吸收" and not r.get("absorb_form"):
            problems.append("可吸收未写 absorb_form")
        if mapping == "需扬弃" and not r.get("reject_reason"):
            problems.append("需扬弃未写 reject_reason")
        if r.get("verify_status") not in ("verified", "unverified"):
            problems.append("verify_status 非法值")
        if any(v is None for k, v in r.items() if k in ("stars", "forks", "contributors")) \
                and r.get("verify_status") == "verified":
            problems.append("指标为 null 却标 verified（违反禁估算）")
    return {"pass": not problems, "problems": problems}


