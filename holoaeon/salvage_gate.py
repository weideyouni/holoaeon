_SKIP_DIR_PREFIXES = ("_", ".")


def discover_salvage_assets(root: str, max_depth: int = 4) -> Dict[str, List[str]]:
    """打捞之王资产自动匹配：在工作区 root 按注册表 pattern 扫描（目录/文件名）。

    纪律：只读不改（原件不移动）；跳过 _/. 前缀目录（历史归档与临时区不
    计入——非归档口径与素材对账一致）；结果确定性（排序输出）。
    """
    matches: Dict[str, List[str]] = {a["id"]: [] for a in SALVAGE_ASSETS}
    patterns = {a["id"]: a["pattern"] for a in SALVAGE_ASSETS if a["pattern"]}
    root = root.rstrip("/\\")
    base_depth = root.count("\\") + root.count("/")
    stack = [(root, base_depth)]
    while stack:
        cur, depth = stack.pop()
        try:
            entries = sorted(_listdir(cur))
        except OSError:
            continue
        for entry in entries:
            path = cur + "/" + entry
            for aid, pat in patterns.items():
                if re.search(pat, entry):
                    matches[aid].append(path)
            if depth - base_depth < max_depth and not entry.startswith(_SKIP_DIR_PREFIXES):
                stack.append((path, depth + 1))
    for aid in matches:
        matches[aid] = sorted(set(matches[aid]))
    return matches


def _listdir(path: str) -> List[str]:
    import os
    return os.listdir(path)


